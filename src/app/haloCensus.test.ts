// The Button call-site halo gate for Phase 88.9 (plan 15 Task 2, SPEC R4, owner option (a)).
//
// WHAT IT PINS
// Every resolved non-card Button call site keeps the halo its ground was ruled to in the 88.9
// halo census, so a later phase that rewires these files (89 and 92 both do) and silently drops,
// misspells or re-chains one call site's halo reds the build instead of shipping a white gap
// around the focus ring.
//
// WHY IT EXISTS BESIDE cascadeOrder TEST 12
// Test 12 judges every chunk that draws a house ring. A Button call site's className carries only
// its own override (focus-visible:ring-offset-surface-page and the like) in a chunk with no ring
// token, because the ring itself lives in the Button primitive, so test 12 never sees it: delete
// a call-site halo and test 12 stays green. halo-check.cjs reads these sites, but it is
// parent-repo planning tooling, not FE CI.
//
// WHY IT IS PER ELEMENT, NEVER PER FILE
// Most tracked non-test src files holding a Button hold more than one: a text grep for the
// opening tag reads 38 of 48 such files (ThemeToggle.js mentions it in a comment only), and by
// JSX element about 33 of the census's 47 (a per-file count over git ls-files at FE 98873d4;
// the user profile page reads 21 and the game detail page 14). A file-level read passes while
// any one Button in it still carries the halo, so each fixture row is located as ONE JSX opening
// element named Button, parsed with the typescript compiler API, and judged on that element's
// own className.
//
// THE FIXTURE
// scripts/baselines/button-halos.json is written by the census generator in its fixture mode,
// run from the parent repo root:
//   node .planning/phases/88.9-fe-look-decisions-design-phase-mockup-gated-split-from-88-6/halo-census-tooling/halo-census.cjs --render-fe-fixture .planning/phases/88.9-fe-look-decisions-design-phase-mockup-gated-split-from-88-6/halo-census-tooling/resolutions.tsv
// which, when this test was written (FE afb37e8), printed 28 entries with excluded
// card-default 114, inset 0, exempt 0, halo-approximate 3, ring-conflict 0, other 0. The file
// sits outside src so the cite walkers never see it, and it is regenerated by that mode in the
// same commit as any later census change; its header note says the same. Its hand_resolved rows
// (the three group-home header Buttons, which the mode excludes as halo-approximate) carry a
// written reason because their className is not static text; regeneration must carry them over.
//
// HOW A ROW IS JUDGED
// The halo reads are the ONE shared copy, src/test-utils/sourceScan.ts ("export function judgeHalo("):
// every token of the row's utility must be a WHOLE token of the className, on the Button ring's
// chain (focus-visible:, or a responsive prefix of it such as md:focus-visible: where the phone
// keeps the card default by ruling), with a declared colour key and no alpha modifier.
//
// WHAT IT CANNOT JUDGE
// Whether the census ground is right for the site: that is the census evidence and Gate C.
// Nor the tinted arm of the group-home header Buttons, which keeps the Button default by design.

import fs from 'node:fs';
import path from 'node:path';

import ts from 'typescript';
import { describe, expect, it } from 'vitest';

import { declaredColorKeys, judgeHalo, readHalo } from '../test-utils/sourceScan';

const FE_ROOT = path.resolve(__dirname, '../..');
const FIXTURE = path.join(FE_ROOT, 'scripts', 'baselines', 'button-halos.json');
const GLOBALS = path.join(__dirname, 'globals.css');

interface Row {
  file: string;
  anchor: string;
  utility: string;
  reason?: string;
  census_id?: string;
}
interface Fixture {
  header: {
    included: number;
    hand_resolved: number;
    excluded: Record<string, number>;
    note: string;
  };
  entries: Row[];
  hand_resolved?: Row[];
}

// The census emitted 28 resolved non-card Button rows at FE afb37e8 (command above). A later
// census may grow it; a fixture that shrinks below it has lost rows.
const CENSUS_ROWS_AT_WRITING = 28;
const HAND_ROWS_AT_WRITING = 3;

// The Button primitive draws its ring on focus-visible:, so a halo applies only on that chain,
// optionally behind one responsive prefix.
const BUTTON_HALO_CHAIN = /^(?:(?:sm|md|lg|xl|2xl):)?focus-visible:$/;

const readFixture = (): Fixture => JSON.parse(fs.readFileSync(FIXTURE, 'utf8')) as Fixture;
const allRows = (fx: Fixture): Row[] => [...fx.entries, ...(fx.hand_resolved ?? [])];
const rowName = (row: Row): string => `${row.file} ("${row.anchor}")`;
const tokensOf = (s: string): string[] => s.split(/\s+/).filter(Boolean);

interface ButtonSite {
  opening: ts.JsxOpeningElement | ts.JsxSelfClosingElement;
  texts: ts.JsxText[];
}

function buttonSites(file: string, src: string): { sf: ts.SourceFile; sites: ButtonSite[] } {
  const kind = /\.tsx$/.test(file) ? ts.ScriptKind.TSX : ts.ScriptKind.JSX;
  const sf = ts.createSourceFile(file, src, ts.ScriptTarget.Latest, true, kind);
  const sites: ButtonSite[] = [];
  const visit = (n: ts.Node): void => {
    if (ts.isJsxSelfClosingElement(n) && n.tagName.getText(sf) === 'Button') {
      sites.push({ opening: n, texts: [] });
    } else if (ts.isJsxElement(n) && n.openingElement.tagName.getText(sf) === 'Button') {
      sites.push({ opening: n.openingElement, texts: n.children.filter(ts.isJsxText) });
    }
    ts.forEachChild(n, visit);
  };
  visit(sf);
  return { sf, sites };
}

// The census anchor is a snippet of the opening tag, or of the Button's own text child. The
// two-part form A >> S names the first occurrence of S after A, where A occurs once in the file.
function anchorSpans(src: string, anchor: string): { spans: [number, number][]; problem?: string } {
  const parts = anchor.split(' >> ');
  if (parts.length === 2) {
    const [head, site] = parts;
    const heads = src.split(head).length - 1;
    if (heads !== 1) return { spans: [], problem: `anchor head occurs ${heads} times, not once` };
    const at = src.indexOf(site, src.indexOf(head) + head.length);
    return at === -1 ? { spans: [] } : { spans: [[at, at + site.length]] };
  }
  const spans: [number, number][] = [];
  for (let at = src.indexOf(anchor); at !== -1; at = src.indexOf(anchor, at + 1)) spans.push([at, at + anchor.length]);
  return { spans };
}

const overlaps = (s: [number, number], start: number, end: number): boolean => s[0] < end && s[1] > start;

function locate(row: Row, src: string): { site?: ButtonSite; sf: ts.SourceFile; problem?: string } {
  const { sf, sites } = buttonSites(row.file, src);
  const { spans, problem } = anchorSpans(src, row.anchor);
  if (problem) return { sf, problem };
  const hits = sites.filter((b) =>
    spans.some(
      (s) =>
        overlaps(s, b.opening.getStart(sf), b.opening.getEnd()) ||
        b.texts.some((t) => overlaps(s, t.getStart(sf), t.getEnd())),
    ),
  );
  if (hits.length !== 1) return { sf, problem: `${hits.length} Button elements carry the anchor, not one` };
  return { sf, site: hits[0] };
}

// The literals a className attribute is built from, and whether it is static text.
function classNameLiterals(site: ButtonSite, sf: ts.SourceFile): { literals: string[]; isStatic: boolean } | null {
  const attr = site.opening.attributes.properties.find(
    (p): p is ts.JsxAttribute => ts.isJsxAttribute(p) && p.name.getText(sf) === 'className',
  );
  if (!attr || !attr.initializer) return null;
  const init = attr.initializer;
  if (ts.isStringLiteral(init)) return { literals: [init.text], isStatic: true };
  if (!ts.isJsxExpression(init) || !init.expression) return null;
  const expr = init.expression;
  if (ts.isStringLiteral(expr) || ts.isNoSubstitutionTemplateLiteral(expr)) return { literals: [expr.text], isStatic: true };
  const literals: string[] = [];
  const visit = (n: ts.Node): void => {
    if (ts.isStringLiteral(n) || ts.isNoSubstitutionTemplateLiteral(n)) literals.push(n.text);
    else if (ts.isTemplateHead(n) || ts.isTemplateMiddle(n) || ts.isTemplateTail(n)) literals.push(n.text);
    ts.forEachChild(n, visit);
  };
  visit(expr);
  return { literals, isStatic: false };
}

// Judge one row against one file's source; returns the failures, each naming the row.
function judgeRow(row: Row, src: string, declared: Set<string>): string[] {
  const name = rowName(row);
  const { site, sf, problem } = locate(row, src);
  if (!site) return [`${name}: ${problem}`];
  const cls = classNameLiterals(site, sf);
  if (!cls) return [`${name}: the Button has no className, so it keeps the card default halo, not ${row.utility}`];
  if (!cls.isStatic && !row.reason) {
    return [`${name}: className is not static text and the row carries no written reason naming the literal that holds the halo`];
  }
  const want = tokensOf(row.utility);
  const chain = readHalo(want[want.length - 1])?.chain ?? '';
  const carriers = cls.literals.filter((lit) => want.every((t) => tokensOf(lit).includes(t)));
  if (carriers.length === 0) return [`${name}: className does not hold ${row.utility} as a whole token`];
  const out: string[] = [];
  for (const lit of carriers) {
    for (const f of judgeHalo(lit, chain, declared)) out.push(`${name}: limb ${f.limb}, ${f.detail}`);
  }
  return out;
}

describe('haloCensus — every resolved non-card Button call site keeps its census halo', () => {
  it('1. the fixture is the census output: rows equal its header counts, never below the census at writing, no line numbers', () => {
    const fx = readFixture();
    expect(fx.entries.length).toBe(fx.header.included);
    expect(fx.header.included).toBeGreaterThanOrEqual(CENSUS_ROWS_AT_WRITING);
    expect((fx.hand_resolved ?? []).length).toBe(fx.header.hand_resolved);
    expect(fx.header.hand_resolved).toBeGreaterThanOrEqual(HAND_ROWS_AT_WRITING);
    expect(fx.header.note).toMatch(/outside src/);
    expect(fx.header.note).toMatch(/same commit as any later census change/);
    // A hand-resolved row is never silent: each carries its written reason.
    const unreasoned = (fx.hand_resolved ?? []).filter((r) => !r.reason || r.reason.length < 40).map(rowName);
    expect(unreasoned).toEqual([]);
    // No line numbers: rows are keyed by anchor only, and no file:line form appears anywhere.
    expect(fs.readFileSync(FIXTURE, 'utf8')).not.toMatch(/\.(?:js|jsx|ts|tsx):\d/);
    const badKeys = allRows(fx).filter((r) => Object.keys(r).some((k) => !['file', 'anchor', 'utility', 'reason', 'census_id'].includes(k)));
    expect(badKeys.map(rowName)).toEqual([]);
    // Every utility is a halo on the Button ring's chain.
    const offChain = allRows(fx)
      .filter((r) => {
        const toks = tokensOf(r.utility);
        const h = readHalo(toks[toks.length - 1]);
        return toks.length !== 1 || !h || h.dark || !BUTTON_HALO_CHAIN.test(h.chain);
      })
      .map((r) => `${rowName(r)}: ${r.utility}`);
    expect(offChain).toEqual([]);
  });

  it('2. every fixture row names exactly one Button opening element in its file', () => {
    const fx = readFixture();
    const problems: string[] = [];
    for (const row of allRows(fx)) {
      const abs = path.join(FE_ROOT, row.file);
      if (!fs.existsSync(abs)) {
        problems.push(`${rowName(row)}: file is gone`);
        continue;
      }
      const { site, problem } = locate(row, fs.readFileSync(abs, 'utf8'));
      if (!site) problems.push(`${rowName(row)}: ${problem}`);
    }
    expect(problems).toEqual([]);
  });

  it('3. every fixture row keeps its census halo on its own Button, judged per element', () => {
    const fx = readFixture();
    const declared = declaredColorKeys(fs.readFileSync(GLOBALS, 'utf8'));
    const failures: string[] = [];
    let read = 0;
    for (const row of allRows(fx)) {
      const abs = path.join(FE_ROOT, row.file);
      if (!fs.existsSync(abs)) {
        failures.push(`${rowName(row)}: file is gone`);
        continue;
      }
      read++;
      failures.push(...judgeRow(row, fs.readFileSync(abs, 'utf8'), declared));
    }
    expect(failures).toEqual([]);
    expect(read).toBe(fx.header.included + fx.header.hand_resolved);
  });

  it('4. the judge reads per element, whole token, on the right chain (negative controls on synthetic source)', () => {
    const declared = new Set(['surface-page', 'surface-card', 'surface-elevated']);
    const src = [
      'export const X = () => (',
      '  <div>',
      '    <Button onClick={keep} className="w-full focus-visible:ring-offset-surface-page">Keep</Button>',
      '    <Button onClick={lost} className="w-full">Lost</Button>',
      '    <Button onClick={peer} className="peer-focus-visible:ring-offset-surface-page">Peer</Button>',
      '    <Button onClick={alpha} className="focus-visible:ring-offset-surface-page/50">Alpha</Button>',
      '    <Button onClick={undeclared} className="focus-visible:ring-offset-status-info-subtle">Undeclared</Button>',
      '    <Button onClick={darkOnly} className="dark:focus-visible:ring-offset-surface-page">Dark</Button>',
      '    <Button onClick={a} className={cn("x", on ? "" : " focus-visible:ring-offset-surface-elevated")}>Arm</Button>',
      '    <Button onClick={twin}>Twin text</Button>',
      '    <Button onClick={twin}>Twin text</Button>',
      '    <Button className="focus-visible:ring-offset-surface-pagex">Only text anchor</Button>',
      '  </div>',
      ');',
    ].join('\n');
    const row = (anchor: string, extra: Partial<Row> = {}): Row => ({
      file: 'synthetic-source',
      anchor,
      utility: 'focus-visible:ring-offset-surface-page',
      ...extra,
    });
    const judge = (r: Row): string[] => judgeRow(r, src, declared);

    // The kept Button passes; its neighbour in the same file reds, by its own anchor.
    expect(judge(row('onClick={keep}'))).toEqual([]);
    expect(judge(row('onClick={lost}'))).toEqual([
      'synthetic-source ("onClick={lost}"): className does not hold focus-visible:ring-offset-surface-page as a whole token',
    ]);
    // Whole token only: the peer- spelling contains the bare one and still reds.
    expect(judge(row('onClick={peer}'))).toHaveLength(1);
    // Alpha and undeclared keys red on limb c; a dark-only halo reds on limb d.
    expect(judge(row('onClick={alpha}', { utility: 'focus-visible:ring-offset-surface-page/50' }))[0]).toMatch(/limb c, .*translucent/);
    expect(judge(row('onClick={undeclared}', { utility: 'focus-visible:ring-offset-status-info-subtle' }))[0]).toMatch(/limb c, .*undeclared/);
    expect(judge(row('onClick={darkOnly}', { utility: 'dark:focus-visible:ring-offset-surface-page' }))[0]).toMatch(/limb d/);
    // A non-static className with no written reason reds; with one, its carrying arm is judged.
    const arm = row('onClick={a}', { utility: 'focus-visible:ring-offset-surface-elevated' });
    expect(judge(arm)[0]).toMatch(/not static text/);
    expect(judge({ ...arm, reason: 'the untinted arm literal carries the elevated halo' })).toEqual([]);
    // Two matching elements, or none, red naming the row.
    expect(judge(row('Twin text'))[0]).toMatch(/2 Button elements carry the anchor/);
    expect(judge(row('onClick={absent}'))[0]).toMatch(/0 Button elements carry the anchor/);
    // An anchor taken from a text child is matched against that Button's own text child.
    expect(judge(row('Only text anchor'))).toEqual([
      'synthetic-source ("Only text anchor"): className does not hold focus-visible:ring-offset-surface-page as a whole token',
    ]);
  });
});
